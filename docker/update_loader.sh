#!/bin/sh
set -e

# ==============================================================================
# Tự động scan các thư mục con trong pkg/scenarios/ và sinh file cmd/ramp/loader.go
# ==============================================================================
APP_DIR="${1:-/app}"
if [ ! -d "$APP_DIR" ] || [ ! -d "$APP_DIR/pkg/scenarios" ]; then
    if [ -d "pkg/scenarios" ]; then
        APP_DIR="."
    fi
fi

LOADER_FILE="$APP_DIR/cmd/ramp/loader.go"
SCENARIOS_DIR="$APP_DIR/pkg/scenarios"

IMPORTS=""
if [ -d "$SCENARIOS_DIR" ]; then
    for dir in "$SCENARIOS_DIR"/*/; do
        [ -d "$dir" ] || continue
        # Kiểm tra xem thư mục có chứa ít nhất một file .go không
        if ls "$dir"*.go >/dev/null 2>&1; then
            pkg_name=$(basename "$dir")
            IMPORTS="${IMPORTS}\n\t_ \"capsizer/pkg/scenarios/${pkg_name}\""
        fi
    done
fi

mkdir -p "$(dirname "$LOADER_FILE")"
if [ -n "$IMPORTS" ]; then
    printf "// Code generated by capsizer; DO NOT EDIT.\npackage main\n\nimport (%b\n)\n" "$IMPORTS" > "$LOADER_FILE"
else
    printf "// Code generated by capsizer; DO NOT EDIT.\npackage main\n" > "$LOADER_FILE"
fi
