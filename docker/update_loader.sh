#!/bin/sh
set -e

# ==============================================================================
# Tự động scan các thư mục con trong scenarios/ và sinh file loader.go
# ==============================================================================
# Giúp người dùng có thể tạo mỗi service một folder trong scenarios/ (ví dụ:
# scenarios/auth/, scenarios/order/, scenarios/payment/), mỗi folder chứa nhiều file .go,
# mà không cần phải viết code import thủ công trong main.go.
# ==============================================================================

APP_DIR="${1:-/app}"
if [ ! -d "$APP_DIR" ] || [ ! -f "$APP_DIR/main.go" ]; then
    if [ -f "ramps/golang/main.go" ]; then
        APP_DIR="ramps/golang"
    elif [ -f "main.go" ]; then
        APP_DIR="."
    fi
fi

LOADER_FILE="$APP_DIR/loader.go"
SCENARIOS_DIR="$APP_DIR/scenarios"

IMPORTS=""
if [ -d "$SCENARIOS_DIR" ]; then
    for dir in "$SCENARIOS_DIR"/*/; do
        [ -d "$dir" ] || continue
        # Kiểm tra xem thư mục có chứa ít nhất một file .go không
        if ls "$dir"*.go >/dev/null 2>&1; then
            pkg_name=$(basename "$dir")
            IMPORTS="${IMPORTS}\n\t_ \"ramps/golang/scenarios/${pkg_name}\""
        fi
    done
fi

if [ -n "$IMPORTS" ]; then
    printf "// Code generated by capsizer; DO NOT EDIT.\npackage main\n\nimport (%b\n)\n" "$IMPORTS" > "$LOADER_FILE"
else
    printf "// Code generated by capsizer; DO NOT EDIT.\npackage main\n" > "$LOADER_FILE"
fi
